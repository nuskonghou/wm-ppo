"""Data of the initial world model without extra interaction: the executed transitions of the PPO warm-up (iterations
1-12 of runs/ppo), in the record format of train_wm.py (executed actions only).

The warm-up logged token ids, not observation text: every tree (one per task, in task order) gives the episode's action
sequence (decoded from the executed responses); the task's game comes from the warm-up's task order (alf_final.run:
seed-0 shuffle of the train list, cursor 0, 128 tasks in iteration 1, 64 after). The observations are regenerated by
replaying the logged actions (the same steps the warm-up took, nothing new is tried). Every replayed observation is
checked against the observation inside the next logged policy prompt (fraction of its lines found there).
   python wm_from_log.py --run runs/ppo --its 1-12 --out runs/wm_data/warmup_log.jsonl"""
import argparse
import json
import multiprocessing as mp
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))
from env import AlfEnv, game_files  # noqa: E402
from prompts import parse_action, split_task  # noqa: E402
from wmppo import paths  # noqa: E402

TOK = None


def tok():
    global TOK
    if TOK is None:
        from transformers import AutoTokenizer
        TOK = AutoTokenizer.from_pretrained(paths.MODEL)
    return TOK


def overlap(text, prompt):
    lines = [l.strip() for l in text.split('\n') if l.strip()]
    return sum(l in prompt for l in lines) / max(1, len(lines))


def episodes_of(tree):
    """Root-to-leaf chains of a warmup tree file (one chain per task): [(root prompt ids, [(prompt ids, resp ids)])]."""
    nodes, edges = tree['nodes'], tree['edges']
    out_e = {}
    for e in edges:
        out_e.setdefault(e['node'], []).append(e)
    is_child = {e['child'] for e in edges if e['child'] is not None}
    eps = []
    for r in range(len(nodes)):
        if r in is_child or r not in out_e:
            continue
        steps, n = [], r
        while n is not None and n in out_e:
            e = out_e[n][0]
            steps.append((nodes[n]['prompt_ids'], e['resp']))
            n = None if e['term'] else e['child']
        eps.append((nodes[r]['prompt_ids'], steps))
    return eps


def replay(job):
    gf, steps, max_steps = job['gamefile'], job['steps'], job['max_steps']
    t = tok()
    env = AlfEnv(gf, max_steps=max_steps)
    try:
        obs, adm = env.reset(); task, room = split_task(obs)
        root = t.decode(steps[0][0])
        if overlap(room, root) < 0.8:
            return {'gamefile': gf, 'mismatch_root': True}
        hist, cur, recs, ov = [], room, [], []
        r, done = 0.0, False
        for k, (p_ids, resp) in enumerate(steps):
            action = parse_action(t.decode(resp), adm)[0]
            prev = (cur, adm, [list(x) for x in hist])
            hist.append((cur, action))
            cur, adm, r, done = env.step(action)
            if k + 1 < len(steps):
                ov.append(overlap(cur, t.decode(steps[k + 1][0])))
            recs.append({'task': task, 'room': room, 'hist': prev[2], 'obs': prev[0], 'adm': prev[1], 'action': action,
                         'next_obs': cur, 'next_adm': adm, 'done': done, 'won': bool(done and r > 0), 'executed': True,
                         'count': 1, 'game': gf, 't': len(prev[2])})
            if done:
                break
        for x in recs:
            x['episode_reward'] = r
        return {'gamefile': gf, 'recs': recs, 'overlap': ov, 'n_logged': len(steps)}
    finally:
        try: env.env.close()               # textworld keeps resources per game
        except Exception: pass  # noqa: E722


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--run', default=os.path.join(HERE, 'runs/ppo'))
    ap.add_argument('--its', default='1-12')
    ap.add_argument('--out', required=True)
    ap.add_argument('--max-steps', type=int, default=40)
    ap.add_argument('--workers', type=int, default=40)
    ap.add_argument('--seed', type=int, default=0)
    a = ap.parse_args()
    lo, hi = (int(x) for x in a.its.split('-'))
    train = game_files('train'); order = list(range(len(train))); random.Random(a.seed).shuffle(order)
    jobs, cursor = [], 0
    for it in range(1, hi + 1):
        n = 128 if it == 1 else 64
        tasks = [train[order[(cursor + k) % len(order)]] for k in range(n)]
        cursor += n
        if it < lo:
            continue
        eps = episodes_of(json.load(open(os.path.join(a.run, f'it{it:03d}', 'tree.json'))))
        assert len(eps) == len(tasks), (it, len(eps), len(tasks))   # no failed episode in the warmup
        jobs += [{'gamefile': g, 'steps': s, 'max_steps': a.max_steps, 'it': it} for g, (_, s) in zip(tasks, eps)]
    with mp.get_context('fork').Pool(a.workers, maxtasksperchild=8) as p:
        res = p.map(replay, jobs, chunksize=1)
    n_rec = mism = short = 0; ov = []
    with open(a.out, 'w') as f:
        for r in res:
            if r.get('mismatch_root'):
                mism += 1; continue
            short += int(len(r['recs']) < r['n_logged'])
            ov += r['overlap']
            for x in r['recs']:
                f.write(json.dumps(x) + '\n'); n_rec += 1
    print(json.dumps({'episodes': len(jobs), 'root_mismatch': mism, 'ended_early_on_replay': short, 'transitions': n_rec,
                      'obs_line_overlap_mean': round(sum(ov) / max(1, len(ov)), 4),
                      'obs_exact_frac': round(sum(x == 1.0 for x in ov) / max(1, len(ov)), 4)}), flush=True)


if __name__ == '__main__':
    main()
