"""Text Sokoban with the interface of alfworld/env.py (so rollout.py, alf_final.py and ct_infer.py run unchanged):
AlfEnv(gamefile).reset() -> (obs, adm), .step(a) -> (obs, adm, reward, done), .replay(); plus mc_value for the ProAct
MC-PPO baseline.

Levels are verl-agent's text Sokoban: 6x6, 1 box, generated by sokoban_gen.generate_room from a seed (search_depth
30, num_gen_steps int(1.7 * 12)), rendered with verl-agent's symbols (# wall, _ floor, O target, X box, √ box on target,
P player, S player on target). Reward 1 when the box is on the target, else 0; an episode ends on success or after
max_steps (15). An action outside the four moves leaves the state unchanged and costs a step.
A "gamefile" is the string '<split>/<seed>/level' (split in train / valid), so evaluate() keys games as 'valid/<seed>'.
data/levels.json holds the seed lists and optimal solution lengths (make_levels)."""
import json
import os
import random
from collections import deque

import numpy as np

import sokoban_gen

HERE = os.path.dirname(os.path.abspath(__file__))
DIM, NUM_BOXES, SEARCH_DEPTH = (6, 6), 1, 30
NUM_GEN_STEPS = int(1.7 * (DIM[0] + DIM[1]))
ACTIONS = ['up', 'down', 'left', 'right']
MOVE = {'up': (-1, 0), 'down': (1, 0), 'left': (0, -1), 'right': (0, 1)}
SYM = {0: '#', 1: '_', 2: 'O', 3: '√', 4: 'X', 5: 'P', 6: 'S'}
EVAL_SPLITS = ('valid',)
TRAIN_SEEDS, VALID_BASE, N_VALID = 20000, 10_000_000, 300
LEVELS = os.path.join(HERE, 'data', 'levels.json')     # seed lists and optimal solution lengths (make_levels)


def generate(seed):
    """(room_fixed, room_state) for a seed; deterministic across processes (verl-agent retries with Python's
    salted str hash; here the retry seed is a fixed function of the seed)."""
    for attempt in range(20):
        s = (seed + 1_000_003 * attempt) % (2 ** 32)
        rs, nrs = random.getstate(), np.random.get_state()
        try:
            random.seed(s); np.random.seed(s)
            fixed, state, _, _ = sokoban_gen.generate_room(dim=DIM, num_steps=NUM_GEN_STEPS, num_boxes=NUM_BOXES,
                                                          search_depth=SEARCH_DEPTH)
            return fixed.astype(int), state.astype(int)
        except (RuntimeError, RuntimeWarning):
            continue
        finally:
            random.setstate(rs); np.random.set_state(nrs)
    raise RuntimeError(f'no level for seed {seed}')


def render(fixed, player, boxes):
    rows = []
    for i in range(fixed.shape[0]):
        cells = []
        for j in range(fixed.shape[1]):
            tgt = fixed[i, j] == 2
            if (i, j) == player:
                c = 6 if tgt else 5
            elif (i, j) in boxes:
                c = 3 if tgt else 4
            else:
                c = 0 if fixed[i, j] == 0 else (2 if tgt else 1)
            cells.append(SYM[c])
        rows.append(' '.join(cells))
    return '\n'.join(rows)


def parse_level(fixed, state):
    player = tuple(int(x) for x in np.argwhere(state == 5)[0])
    boxes = {tuple(int(x) for x in p) for p in np.argwhere((state == 3) | (state == 4))}
    return player, boxes


def move(fixed, player, boxes, a):
    """One step of Sokoban dynamics; returns (player, boxes)."""
    if a not in MOVE:
        return player, boxes
    di, dj = MOVE[a]
    nxt = (player[0] + di, player[1] + dj)
    if fixed[nxt] == 0:
        return player, boxes
    if nxt in boxes:
        beyond = (nxt[0] + di, nxt[1] + dj)
        if fixed[beyond] == 0 or beyond in boxes:
            return player, boxes
        boxes = (boxes - {nxt}) | {beyond}
    return nxt, boxes


def solved(fixed, boxes):
    return all(fixed[b] == 2 for b in boxes)


def optimal_length(fixed, state, cap=60):
    """BFS over (player, boxes); None if not solvable within cap moves."""
    start = parse_level(fixed, state)
    start = (start[0], frozenset(start[1]))
    seen, q = {start: 0}, deque([start])
    while q:
        s = q.popleft()
        if solved(fixed, s[1]):
            return seen[s]
        if seen[s] >= cap:
            continue
        for a in ACTIONS:
            p, b = move(fixed, s[0], set(s[1]), a)
            n = (p, frozenset(b))
            if n not in seen:
                seen[n] = seen[s] + 1; q.append(n)
    return None


def make_levels():
    """data/levels.json: validation seeds VALID_BASE.. (N_VALID levels), training seeds 0.. (TRAIN_SEEDS levels)
    excluding any training level identical to a validation level; optimal solution length of each."""
    os.makedirs(os.path.dirname(LEVELS), exist_ok=True)
    val, keys = [], set()
    for k in range(N_VALID):
        s = VALID_BASE + k; f, st = generate(s)
        val.append({'seed': s, 'opt': optimal_length(f, st)}); keys.add((f.tobytes(), st.tobytes()))
    train, dup = [], 0
    for s in range(TRAIN_SEEDS):
        f, st = generate(s)
        if (f.tobytes(), st.tobytes()) in keys:
            dup += 1; continue
        train.append({'seed': s, 'opt': optimal_length(f, st)})
    json.dump({'valid': val, 'train': train, 'train_dropped_as_valid_duplicates': dup}, open(LEVELS, 'w'))
    return dup


def _levels():
    if not os.path.exists(LEVELS):
        make_levels()
    return json.load(open(LEVELS))


def game_files(split):
    return [f"{split}/{x['seed']}/level" for x in _levels()[split]]


def _opt(gamefile):
    split, seed = gamefile.split('/')[:2]
    return {x['seed']: x['opt'] for x in _levels()[split]}.get(int(seed))


def task_type(gamefile):
    """Bucket of the optimal solution length (moves)."""
    o = _opt(gamefile)
    if o is None:
        return 'unsolvable'
    return 'opt1-3' if o <= 3 else 'opt4-6' if o <= 6 else 'opt7-10' if o <= 10 else 'opt11+'


class AlfEnv:
    def __init__(self, gamefile, max_steps=15):
        self.gamefile = gamefile
        self.seed = int(gamefile.split('/')[1])
        self.max_steps = max_steps
        self.fixed, self.state0 = generate(self.seed)

    def reset(self):
        self.player, self.boxes = parse_level(self.fixed, self.state0)
        self.t = 0
        return render(self.fixed, self.player, self.boxes), list(ACTIONS)

    def step(self, action):
        self.player, self.boxes = move(self.fixed, self.player, self.boxes, action)
        self.t += 1
        won = solved(self.fixed, self.boxes)
        done = won or self.t >= self.max_steps
        return render(self.fixed, self.player, self.boxes), list(ACTIONS), float(won), done

    def mc_value(self, M=1000, T=15, gamma=0.95):
        """ProAct's Monte-Carlo critic (envs/sokobanEnv.py get_value_from_state_sokoban): mean
        discounted return of M rollouts of at most T uniformly random moves from a copy of the current state, a rollout
        ending when the box is on the target; with this environment's 0/1 reward a rollout returns gamma**j if it
        solves the level at its (j+1)-th move, else 0. The episode itself is not changed."""
        fixed, rnd = self.fixed, random.random
        if solved(fixed, self.boxes):
            return 0.0
        total = 0.0
        for _ in range(M):
            player, boxes, disc = self.player, set(self.boxes), 1.0
            for _j in range(T):
                player, boxes = move(fixed, player, boxes, ACTIONS[int(rnd() * 4)])
                if solved(fixed, boxes):
                    total += disc
                    break
                disc *= gamma
        return total / M

    def close(self):
        """No resources to release (interface of the ScienceWorld env, whose callers close every episode)."""

    def replay(self, actions):
        obs, adm = self.reset()
        r, done = 0.0, False
        for a in actions:
            obs, adm, r, done = self.step(a)
            if done:
                break
        return obs, adm, r, done


